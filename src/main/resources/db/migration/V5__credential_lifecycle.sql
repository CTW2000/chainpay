-- ----------------------------------------------------------------------------
-- label —— 这把钥匙是哪把？
--
-- ★ 它是「零停机轮换」能落地的前提 ★
--
-- 轮换的流程是：
--   ① 发一把新的       → 商户此刻有 2 把有效凭证
--   ② 把新 key 部署上去 → 流量逐渐切过去
--   ③ 确认旧 key 没流量  → 看 last_used_at
--   ④ 吊销旧 key        → 全程零中断
--
-- 第 ④ 步商户要回答「我该吊销哪一把」。只有 api_key（ak_7f3c...）的话，
-- 他得自己去比对哪个是旧的 —— 而吊销错一把就是一次生产事故。
-- 一个人能读懂的名字（"生产-主"、"2026-08轮换"）把这个判断变成显然的。
--
-- 允许为空：老数据没有 label，不该因此让迁移失败。
-- ----------------------------------------------------------------------------
ALTER TABLE api_credential ADD COLUMN label TEXT;


-- ----------------------------------------------------------------------------
-- revoked_at —— 什么时候被吊销的？
--
-- status='REVOKED' 只告诉我们「现在是死的」，答不出「什么时候死的」。
-- 而安全事故复盘时问的恰恰是后者：
--   "泄露发生在 8 月 3 日，那把 key 是 8 月 5 日才吊销的"
--   → 中间 2 天的所有请求都要逐条审查
--
-- 光有 status 的话，这个问题只能靠翻应用日志回答，而日志会滚掉。
-- ----------------------------------------------------------------------------
ALTER TABLE api_credential ADD COLUMN revoked_at TIMESTAMPTZ;


-- ----------------------------------------------------------------------------
-- 状态和时间戳必须一致
--
-- ★ 能让数据库守的，不要交给应用（CLAUDE.md §2）★
--
-- 没有这条约束的话，下面两种坏数据都能存进去，而且不会有任何报错：
--   status='REVOKED' 但 revoked_at 是 NULL  → 审计查不出吊销时间
--   status='ACTIVE'  但 revoked_at 有值      → 这把 key 到底能不能用？
--
-- 第二种尤其危险：两个字段互相矛盾时，读代码的人和写代码的人
-- 可能各信一个。约束让这种状态**根本存不进去**。
-- ----------------------------------------------------------------------------
ALTER TABLE api_credential
    ADD CONSTRAINT api_credential_revoked_ck CHECK (
        (status = 'REVOKED' AND revoked_at IS NOT NULL)
     OR (status = 'ACTIVE'  AND revoked_at IS NULL)
    );


COMMENT ON COLUMN api_credential.label      IS '人读的名字，用于轮换时分辨该吊销哪一把';
COMMENT ON COLUMN api_credential.revoked_at IS '吊销时刻。事故复盘要回答「泄露到吊销之间有多久」';
