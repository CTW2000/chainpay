--   开发：docker-compose 把本目录挂到 /docker-entrypoint-initdb.d/，首次建库时跑
--   测试：AbstractPostgresTest 把本文件拷进 Testcontainers 容器的同一目录
--   生产：DBA 用同样的语句、不同的密码
--
-- ★ 为什么角色不放在 Flyway 里 ★
-- 角色是集群级对象、带密码。迁移是模式级对象、进 git。
-- 密码不能进 git，所以角色不能由迁移创建——V6 之前是这么做的（NOLOGIN 无密码），
-- 那是因为当时应用以超级用户连库、只在事务内 SET LOCAL ROLE 临时切过去。
-- 2026-08-31 质询扫描证明那条路是错的：忘了切就以超级用户跑，RLS 整套失效且零报错。
--
-- 应用现在直接以这个角色连库。它**不是**超级用户、**不是**表的所有者，
-- RLS 对它无条件生效，忘了设租户 = 一行都看不到。
--
-- 这里的密码只用于开发和测试。生产环境由 DBA 另设，并通过 CHAINPAY_DB_PASSWORD 注入。
-- ============================================================================
